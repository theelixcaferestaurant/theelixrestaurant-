// Usage:  npm run assets:check            (writes ASSETS-CHECKLIST.md and tools/media-brief.json)
//         npm run assets:check -- --strict   (exit code 1 while anything is PENDING; use before a release)
// Every required file is marked PASS (present and within its size budget) or PENDING (missing or too large).
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, parse } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const menuSrc = readFileSync(join(root, 'src/data/menuData.js'), 'utf8');
const galSrc = readFileSync(join(root, 'src/data/galleryData.js'), 'utf8');
const Q = "'((?:[^'\\\\]|\\\\.)*)'";
const items = [...menuSrc.matchAll(new RegExp(`make\\('([a-z0-9-]+)',\\s*${Q},\\s*'([a-z]+)',\\s*${Q},\\s*(\\d+),\\s*(\\w+),\\s*${Q}`, 'g'))]
  .map((m) => ({ id: m[1], name: m[2], category: m[3], sub: m[4], desc: m[7].replace(/\\'/g, "'") }));
const gallery = [...galSrc.matchAll(/\{ id: '([a-z0-9-]+)', title: '([^']+)', group: '([^']+)'(?:, itemId: '([a-z0-9-]+)')?/g)]
  .map((m) => ({ id: m[1], title: m[2], group: m[3], itemId: m[4] || null }));

// Size budgets (bytes): keeps mobile loading fast.
const BUDGET = { photo: 400 * 1024, clip: 2.5 * 1024 * 1024, heroClip: 6 * 1024 * 1024, heroPoster: 300 * 1024 };

const scan = (dir, exts) => {
  const map = new Map();
  if (!existsSync(dir)) return map;
  for (const f of readdirSync(dir, { recursive: true })) {
    const p = parse(String(f));
    if (exts.includes(p.ext.toLowerCase())) map.set(p.name.toLowerCase(), statSync(join(dir, String(f))).size);
  }
  return map;
};
const images = scan(join(root, 'src/assets/images'), ['.jpg', '.jpeg', '.png', '.webp', '.avif']);
const videos = scan(join(root, 'src/assets/videos'), ['.mp4', '.webm']);
const pub = (name) => {
  const p = join(root, 'public/video', name);
  return existsSync(p) ? statSync(p).size : null;
};

let pass = 0, pending = 0;
const status = (size, limit) => {
  if (size == null) { pending++; return 'PENDING (missing)'; }
  if (size > limit) { pending++; return `PENDING (too large: ${(size / 1024).toFixed(0)} KB, run tools/optimize-media.sh)`; }
  pass++; return 'PASS';
};

let out = '# THE ELIX: asset checklist\n\nGenerated by `npm run assets:check`. PASS = file present and within its size budget. PENDING = missing or too large.\nPhotos go in `src/assets/images/` (jpg, png, webp or avif), clips in `src/assets/videos/` (mp4 and optional webm).\nHero video files go in `public/video/`. Names must match exactly (case-insensitive, any image extension).\n\n';

out += '## 1. Menu item photographs (40)\n\n| Item | File (any of jpg/webp/avif/png) | Status |\n|---|---|---|\n';
for (const it of items) out += `| ${it.name} | ${it.id} | ${status(images.get(it.id), BUDGET.photo)} |\n`;

out += '\n## 2. Menu item hover/tap clips (40)\n\n| Item | File | Status |\n|---|---|---|\n';
for (const it of items) out += `| ${it.name} | ${it.id}.mp4 | ${status(videos.get(it.id), BUDGET.clip)} |\n`;

out += '\n## 3. Category banners (4)\n\n| File | Status |\n|---|---|\n';
for (const k of ['category-chai', 'category-tiffins', 'category-bakery', 'category-food']) out += `| ${k} | ${status(images.get(k), BUDGET.photo)} |\n`;

out += '\n## 4. Website images (9: 13 with the 4 banners above)\n\n| File | Used for | Status |\n|---|---|---|\n';
const site = [
  ['hero-main', 'Home hero image (also the still under the hero video)'], ['hero-accent', 'Home hero small image'],
  ['welcome', 'Home brand introduction'], ['ambience', 'Home ambience banner'],
  ['about-story', 'About page'], ['about-ambience', 'About page'],
  ['gallery-interior-1', 'Gallery: Main dining area'], ['gallery-interior-2', 'Gallery: Tea lounge corner'], ['gallery-interior-3', 'Gallery: Bakery counter'],
];
for (const [k, use] of site) out += `| ${k} | ${use} | ${status(images.get(k), BUDGET.photo)} |\n`;

out += `\n## 5. Gallery entries (${gallery.length})\nFood entries reuse the matching menu photograph (section 1); interior entries use section 4.\n\n| Entry | Needs | Status |\n|---|---|---|\n`;
for (const g of gallery) {
  const keys = [`gallery-${g.id}`, g.itemId].filter(Boolean);
  const size = keys.map((k) => images.get(k)).find((s) => s != null);
  out += `| ${g.title} | ${keys.join(' or ')} | ${status(size, BUDGET.photo)} |\n`;
}

out += '\n## 6. Home hero video (`public/video/`)\n\n| File | Status |\n|---|---|\n';
out += `| hero-food.mp4 (required) | ${status(pub('hero-food.mp4'), BUDGET.heroClip)} |\n`;
out += `| hero-food.webm (recommended fallback) | ${status(pub('hero-food.webm'), BUDGET.heroClip)} |\n`;
out += `| hero-food-poster.jpg (recommended) | ${status(pub('hero-food-poster.jpg'), BUDGET.heroPoster)} |\n`;

out += '\n## 7. Intro (already supplied)\n\n| File | Status |\n|---|---|\n';
for (const f of ['elix-intro.mp4', 'elix-intro.webm', 'elix-intro-first.jpg', 'elix-logo-final.jpg']) out += `| ${f} | ${pub(f) ? (pass++, 'PASS') : (pending++, 'PENDING (missing)')} |\n`;

out += `\n---\n**Total: ${pass} PASS, ${pending} PENDING.** ${pending ? 'The project is NOT media-complete.' : 'All media present.'}\n`;
writeFileSync(join(root, 'ASSETS-CHECKLIST.md'), out);

// A ready-to-use brief, so a photographer or an image/video generator can be run once per item, no duplicates.
const brief = {
  note: 'One photo and one 4-6 s clip per item. Photo 4:5 portrait, 1200 px wide. Clip 4:5, 720 px wide, no audio, slow camera move or natural motion (steam, pour, drizzle, slice). The clip must start on the same framing as the photo.',
  items: items.map((it) => ({
    id: it.id, photo: `${it.id}.jpg`, clip: `${it.id}.mp4`,
    prompt: `Photorealistic professional food photograph of ${it.name} (${it.sub}): ${it.desc} Natural light, shallow depth of field, authentic South Indian cafe styling, no text, no logos, no hands.`,
  })),
  site: Object.fromEntries(site.map(([k, use]) => [k, use])),
  hero: 'hero-food.mp4: 8-12 s seamless loop, 4:5 portrait, 1080x1350, muted, slow cinematic push-in on a signature dish with rising steam.',
};
writeFileSync(join(root, 'tools/media-brief.json'), JSON.stringify(brief, null, 2));

console.log(`Menu items parsed: ${items.length}   Gallery entries parsed: ${gallery.length}`);
console.log(`${pass} PASS, ${pending} PENDING  ->  ASSETS-CHECKLIST.md`);
if (process.argv.includes('--strict') && pending) process.exit(1);
